// DISC-IG-P0-01.3: packs the Instagram helper (extensions/instagram-helper) into the zip
// that WonderArk's install page offers for download, and writes it into a generated module
// (base64), so the download is served from the app's own code and always matches the
// extension's source. `npm run build:instagram-helper` after changing the extension;
// scripts/instagram-helper.test.mjs fails when the generated module is stale.
//
// The zip is written here (stored, not compressed; fixed dates) so the same source always
// gives the same bytes on any machine, and no dependency is needed for a dozen kilobytes.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const HELPER_DIR = join(root, "extensions", "instagram-helper");
export const GENERATED_PATH = join(root, "packages", "module-discovery", "src", "lib", "instagram-helper", "package.generated.ts");
/** What ships. The mock test and anything else in the folder does not. */
export const HELPER_FILES = ["manifest.json", "lib.js", "background.js", "content.js", "ark.js", "popup.html", "popup.js", "README.md"];
const FOLDER = "wonderark-instagram-helper";

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

/** A zip of the given files, stored uncompressed, with a fixed date (1 Jan 2026). */
export function zipOf(files) {
  const DATE = ((2026 - 1980) << 9) | (1 << 5) | 1;
  const locals = [];
  const central = [];
  let offset = 0;
  for (const { name, data } of files) {
    const nameBytes = Buffer.from(name, "utf8");
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0x0800, 6); // names are UTF-8
    local.writeUInt16LE(0, 8); // stored
    local.writeUInt16LE(0, 10); // time
    local.writeUInt16LE(DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    locals.push(local, nameBytes, data);
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0);
    entry.writeUInt16LE(20, 4);
    entry.writeUInt16LE(20, 6);
    entry.writeUInt16LE(0x0800, 8);
    entry.writeUInt16LE(0, 10);
    entry.writeUInt16LE(0, 12);
    entry.writeUInt16LE(DATE, 14);
    entry.writeUInt32LE(crc, 16);
    entry.writeUInt32LE(data.length, 20);
    entry.writeUInt32LE(data.length, 24);
    entry.writeUInt16LE(nameBytes.length, 28);
    entry.writeUInt32LE(offset, 42);
    central.push(entry, nameBytes);
    offset += 30 + nameBytes.length + data.length;
  }
  const centralBytes = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(centralBytes.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, centralBytes, end]);
}

/** The generated module's text for the extension as it is on disk. */
export function generatedModule() {
  const files = HELPER_FILES.map((file) => ({ name: `${FOLDER}/${file}`, data: readFileSync(join(HELPER_DIR, file)) }));
  const { version } = JSON.parse(readFileSync(join(HELPER_DIR, "manifest.json"), "utf8"));
  const base64 = zipOf(files).toString("base64");
  return `// GENERATED by scripts/build-instagram-helper.mjs from extensions/instagram-helper. Do not edit:
// run \`npm run build:instagram-helper\`. (DISC-IG-P0-01.3)

/** The helper's version, from its manifest. */
export const HELPER_VERSION = ${JSON.stringify(version)};
/** The file name the download is saved as. */
export const HELPER_ZIP_NAME = "${FOLDER}-${version}.zip";
/** The extension's files, zipped (stored), as base64. */
export const HELPER_ZIP_BASE64 =
  ${JSON.stringify(base64)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(GENERATED_PATH, generatedModule());
  console.log(`build:instagram-helper — ${HELPER_FILES.length} files packed.`);
}
